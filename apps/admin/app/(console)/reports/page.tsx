import Link from "next/link";
import { createClient } from "@/lib/supabase/server";

export default async function ReportsPage() {
  const supabase = await createClient();
  const { data: orgs } = await supabase.from("organizations").select("id, name").order("name").limit(50);

  return (
    <section className="flex flex-col gap-6">
      <h1 className="font-display text-3xl text-midnight">Reports</h1>
      <p className="text-text-muted text-sm">
        Collections, occupancy and overdue ageing are generated by the{" "}
        <code>report_*</code> RPCs scoped to an organization.
      </p>
      <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-4">
        {(orgs ?? []).map((o) => (
          <Link key={o.id} href={`/reports/${o.id}`} className="card p-5 hover:border-royal">
            <p className="font-semibold text-navy">{o.name}</p>
            <p className="text-xs text-text-muted mt-1">Collections · occupancy · ageing</p>
          </Link>
        ))}
      </div>
    </section>
  );
}
